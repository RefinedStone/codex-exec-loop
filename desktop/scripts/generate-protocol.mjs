#!/usr/bin/env node
// `codex app-server generate-ts` 로 프로토콜 타입을 만들고 src/shared/protocol/generated 에 복사한다 (P-06).
// 안정 API 만 생성한다 (P-07). 생성에 쓴 codex 버전은 src/shared/protocol/version.ts 에 기록한다.
// 생성 파일은 손으로 고치지 않는다. codex 를 업그레이드하면 이 스크립트를 다시 실행한다.
// usage: node scripts/generate-protocol.mjs [codex executable]
import { execFileSync } from "node:child_process";
import { cpSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const desktopRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const protocolRoot = join(desktopRoot, "src", "shared", "protocol");
const generatedRoot = join(protocolRoot, "generated");
const codex = process.argv[2] ?? "codex";
// npm 이 설치한 Windows codex 는 .cmd 래퍼라서 shell 로만 실행된다. 이때는 인자를 직접 따옴표로 감싼다.
const useShell = process.platform === "win32";
const quote = (value) => (useShell ? `"${value.replaceAll('"', '\\"')}"` : value);
const runCodex = (args) =>
  useShell
    ? execFileSync([codex, ...args].map(quote).join(" "), { encoding: "utf8", shell: true })
    : execFileSync(codex, args, { encoding: "utf8" });

const version = runCodex(["--version"]).trim();
const scratch = mkdtempSync(join(tmpdir(), "akra-desktop-protocol-"));
try {
  runCodex(["app-server", "generate-ts", "--out", scratch]);
  rmSync(generatedRoot, { recursive: true, force: true });
  cpSync(scratch, generatedRoot, { recursive: true });
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
writeFileSync(
  join(protocolRoot, "version.ts"),
  `// generated by scripts/generate-protocol.mjs; do not edit\nexport const GENERATED_CODEX_VERSION = ${JSON.stringify(version)};\n`,
);
console.log(`generated protocol types from ${version} into ${generatedRoot}`);
