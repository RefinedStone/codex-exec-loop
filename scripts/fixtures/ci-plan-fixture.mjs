import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

export const fixtureToolchain = { cargo: "fixture cargo 1", rustc: "fixture rustc 1" };
const inheritedEnvironment = () => Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.toUpperCase().startsWith("GIT_")));
export function fixtureGit(cwd, args) {
  return execFileSync("git", ["--no-optional-locks", "-C", cwd, ...args], {
    env: inheritedEnvironment(), encoding: "utf8", stdio: ["ignore", "pipe", "pipe"],
  });
}
export function writeFixtureFile(cwd, path, content) {
  const target = join(cwd, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
}
export function fixtureMetadata(cwd) {
  const ownership = JSON.parse(readFileSync(join(cwd, "scripts/ci-crate-ownership.json"), "utf8"));
  const entries = ownership.packages.filter((entry) => entry.state === "active");
  const ids = new Map(entries.map((entry, index) => [entry.name, "fixture opaque ID " + index + " " + cwd]));
  const packages = entries.map((entry) => ({
    id: ids.get(entry.name), name: entry.name, version: "0.1.0", source: null,
    manifest_path: join(cwd, entry.manifest), features: {},
    dependencies: entry.workspaceDependencies.filter((name) => ids.has(name)).map((name) => {
      const destination = entries.find((candidate) => candidate.name === name);
      return { name, path: dirname(join(cwd, destination.manifest)), kind: null, target: null, optional: false, rename: null, features: [] };
    }),
    targets: [{
      name: entry.name.replaceAll("-", "_"), kind: ["lib"], test: true, doctest: true,
      src_path: join(dirname(join(cwd, entry.manifest)), "src/lib.rs"),
    }],
  }));
  return {
    version: 1, workspace_root: cwd, workspace_members: packages.map((pkg) => pkg.id), packages,
    resolve: { root: packages[0].id, nodes: packages.map((pkg) => ({
      id: pkg.id, features: [],
      deps: pkg.dependencies.map((dependency) => ({ name: dependency.name, pkg: ids.get(dependency.name), dep_kinds: [{ kind: null, target: null }] })),
    })) },
  };
}
export function createPlanFixture({ rootConsumesLeaf = false, externalInputs = [], contracts = [], parentDirectory = tmpdir() } = {}) {
  const cwd = mkdtempSync(join(parentDirectory, "akra-local-plan-fixture-"));
  const ownership = {
    schemaVersion: 1, revision: 1, rootPackage: "akra-ade",
    fullInputs: ["Cargo.toml", "Cargo.lock", "scripts/"], contracts,
    packages: [
      { name: "akra-ade", manifest: "Cargo.toml", sourcePrefixes: ["src/"], workspaceDependencies: rootConsumesLeaf ? ["leaf"] : [], externalInputs },
      { name: "leaf", manifest: "crates/leaf/Cargo.toml", sourcePrefixes: ["crates/leaf/"], workspaceDependencies: [], externalInputs: [] },
      { name: "other", manifest: "crates/other/Cargo.toml", sourcePrefixes: ["crates/other/"], workspaceDependencies: [], externalInputs: [] },
    ].map((entry) => ({ state: "active", consumerCoverage: "full", ...entry })),
  };
  const rust = [
    "pub fn value() -> u32 {", "    1", "}", "", "#[cfg(test)]", "mod tests {",
    "    #[test]", "    fn works() {", "        assert_eq!(super::value(), 1);", "    }", "}", "",
  ].join("\n");
  writeFixtureFile(cwd, ".gitignore", "target/\nartifacts/\ngenerated/\ncargo-home/\n");
  writeFixtureFile(cwd, "Cargo.toml", '[package]\nname = "akra-ade"\nversion = "0.1.0"\nedition = "2024"\n\n[workspace]\nmembers = ["crates/leaf", "crates/other"]\nresolver = "3"\n');
  writeFixtureFile(cwd, "Cargo.lock", '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "akra-ade"\nversion = "0.1.0"\n\n[[package]]\nname = "leaf"\nversion = "0.1.0"\n\n[[package]]\nname = "other"\nversion = "0.1.0"\n');
  writeFixtureFile(cwd, "scripts/ci-crate-ownership.json", JSON.stringify(ownership, null, 2) + "\n");
  writeFixtureFile(cwd, "src/lib.rs", rust);
  for (const name of ["leaf", "other"]) {
    writeFixtureFile(cwd, "crates/" + name + "/Cargo.toml", '[package]\nname = "' + name + '"\nversion = "0.1.0"\nedition = "2024"\n');
    writeFixtureFile(cwd, "crates/" + name + "/src/lib.rs", rust);
  }
  writeFixtureFile(cwd, "crates/leaf/src/rename me.rs", "// Rename inventory fixture.\n");
  writeFixtureFile(cwd, "crates/leaf/src/deleted.rs", "// Delete inventory fixture.\n");
  fixtureGit(cwd, ["init", "-q"]);
  fixtureGit(cwd, ["config", "user.name", "Local CI fixture"]);
  fixtureGit(cwd, ["config", "user.email", "ci-fixture@example.invalid"]);
  fixtureGit(cwd, ["config", "core.autocrlf", "false"]);
  fixtureGit(cwd, ["add", "."]);
  fixtureGit(cwd, ["commit", "-qm", "baseline"]);
  fixtureGit(cwd, ["branch", "prerelease"]);
  const baseSha = fixtureGit(cwd, ["rev-parse", "HEAD"]).trim();
  const environment = { ...inheritedEnvironment(), CARGO_HOME: join(cwd, "cargo-home") };
  return {
    cwd, baseSha, environment, ownership,
    services: { environment, toolchainIdentity: () => fixtureToolchain, readMetadata: fixtureMetadata },
    cleanup: () => rmSync(cwd, { recursive: true, force: true, maxRetries: 3, retryDelay: 100 }),
  };
}
