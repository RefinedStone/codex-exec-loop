#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES/rust-crates.txt: the license texts of every crate that the release
// binaries link, for the release targets only. Run it after a dependency change (#2586).
//
//   node scripts/third-party-notices.mjs            # rewrite the file
//   node scripts/third-party-notices.mjs --check    # fail when the file is out of date

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const RELEASE_TARGETS = [
  "x86_64-unknown-linux-gnu",
  "aarch64-apple-darwin",
  "x86_64-pc-windows-msvc",
];
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;
// Crates whose package has no license file: "name version" -> the upstream text at the crate's
// published commit (from its .cargo_vcs_info.json).
const FALLBACK_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "rust-license-fallbacks");

/** Package ids reachable from the root through normal (shipped) dependencies only. */
export function shippedPackageIds(metadata) {
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
  const root = metadata.resolve.root;
  const seen = new Set();
  const stack = [root];
  while (stack.length > 0) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      if (dep.dep_kinds.some((kind) => kind.kind === null)) stack.push(dep.pkg);
    }
  }
  seen.delete(root);
  return seen;
}

/** One section per distinct license text, listing the crates that use it. Fails on a crate without one. */
export function renderNotices(packages, readLicenseTexts) {
  const groups = new Map();
  const missing = [];
  for (const pkg of [...packages].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
    const label = `${pkg.name} ${pkg.version} (${pkg.license ?? "license-file"})`;
    const texts = readLicenseTexts(pkg);
    if (texts.length === 0) {
      missing.push(label);
      continue;
    }
    for (const text of texts) {
      const key = createHash("sha256").update(text).digest("hex");
      const group = groups.get(key) ?? { text, users: [] };
      group.users.push(label);
      groups.set(key, group);
    }
  }
  if (missing.length > 0) {
    throw new Error(
      `no license text for:\n${missing.map((m) => `  ${m}`).join("\n")}\n` +
        "add the upstream text to scripts/rust-license-fallbacks/index.json",
    );
  }
  const sections = [...groups.values()].map(
    (group) => `Used by:\n${group.users.map((user) => `  ${user}`).join("\n")}\n\n${group.text.trim()}\n`,
  );
  const header =
    "Akra ADE: third-party Rust crate licenses\n" +
    "Generated by scripts/third-party-notices.mjs from Cargo.lock for the release targets.\n";
  return `${header}\n${sections.join(`\n${"=".repeat(78)}\n\n`)}`;
}

function readPackageLicenseTexts(pkg) {
  const dir = path.dirname(pkg.manifest_path);
  const files = fs.readdirSync(dir).filter((name) => LICENSE_FILE.test(name)).sort();
  if (pkg.license_file) files.push(path.relative(dir, path.resolve(dir, pkg.license_file)));
  const texts = [...new Set(files)]
    .map((name) => path.join(dir, name))
    .filter((file) => fs.existsSync(file) && fs.statSync(file).isFile())
    .map(readText);
  if (texts.length > 0) return texts;
  const fallbacks = JSON.parse(fs.readFileSync(path.join(FALLBACK_DIR, "index.json"), "utf8"));
  const fallback = fallbacks[`${pkg.name} ${pkg.version}`];
  return fallback ? [readText(path.join(FALLBACK_DIR, fallback.file))] : [];
}

function readText(file) {
  return fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
}

function cargoMetadata(repoRoot, target) {
  const output = execFileSync(
    "cargo",
    ["metadata", "--format-version", "1", "--locked", "--filter-platform", target],
    { cwd: repoRoot, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 },
  );
  return JSON.parse(output);
}

function main() {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const outFile = path.join(repoRoot, "THIRD_PARTY_NOTICES", "rust-crates.txt");
  const packages = new Map();
  for (const target of RELEASE_TARGETS) {
    const metadata = cargoMetadata(repoRoot, target);
    const byId = new Map(metadata.packages.map((pkg) => [pkg.id, pkg]));
    for (const id of shippedPackageIds(metadata)) packages.set(id, byId.get(id));
  }
  const notices = renderNotices(packages.values(), readPackageLicenseTexts);
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== notices) {
      console.error(`${path.relative(repoRoot, outFile)} is out of date; run node scripts/third-party-notices.mjs`);
      process.exit(1);
    }
    return;
  }
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, notices);
  console.log(`wrote ${path.relative(repoRoot, outFile)} (${packages.size} crates)`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
